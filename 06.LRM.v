LRM stands for Language Reference Manual.

In hardware design and verification, it is the official specification document published by IEEE (such as IEEE 1800 for SystemVerilog) that defines the exact rules of the language.

It covers:

Precise syntax and grammar

Semantic behavior (how simulators must execute features like first(), next(), threads, queues, and scheduling)

Built-in functions and system tasks

EDA simulators (like QuestaSim, VCS, or Xcelium) are built to follow the rules defined in the SystemVerilog LRM.
