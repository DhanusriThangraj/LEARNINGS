1. OKAY (2'b00) — Normal Access Success
What it means:

The transaction was delivered to the designated slave, executed without errors, and completed cleanly.

Purpose:

Confirms to the master that:

For writes: The data has been accepted and safely committed into the target register, FIFO, or memory space.

For reads: The returned rdata represents valid data read from the requested address.

Typical scenarios:

Reading a valid status register.

Writing configuration parameters or payload data into memory during standard operation.

2. EXOKAY (2'b01) — Exclusive Access Success
What it means:

An exclusive read or exclusive write operation succeeded as part of an atomic semaphore / read-modify-write operation.

Purpose:

Used by multi-core processors to implement atomic locks, semaphores, and mutexes without locking down the entire bus:

A master issues an exclusive read (ARLOCK = 1 in full AXI). The target slave's internal exclusive monitor starts tracking that memory location for that master ID.

The master modifies the data locally in its core.

The master issues an exclusive write (AWLOCK = 1).

If no other master touched that address in the meantime, the write succeeds and the slave responds with EXOKAY.

If another master wrote to that address first, the lock breaks: the write is aborted or ignored, and the slave responds with OKAY (not EXOKAY), signaling to the master that the atomic transaction failed and must be retried.

  Note on AXI-Lite:

AXI-Lite does not support exclusive accesses (no ARLOCK/AWLOCK signals). Therefore, an AXI-Lite slave must never generate EXOKAY; it treats all successful transfers as OKAY.

3. SLVERR (2'b10) — Slave Error
What it means:

The interconnect successfully routed the request to the target slave, but the slave device itself encountered an unrecoverable condition or rejected the transfer.

Purpose:

Informs the master that communication succeeded up to the peripheral boundary, but the operation violated peripheral rules or hit hardware faults.

Typical scenarios:

Access Permission Violations: Attempting to write to a read-only (RO) register, or an unprivileged transaction trying to access secure memory.

Misaligned Access / Unsupported Transfer Size: Requesting a transfer size or byte mask that the peripheral's internal register interface cannot handle.

Hardware Faults: Parity/ECC checksum errors detected inside the slave memory array.

FIFO Overrun / Underrun: Accessing an internal FIFO or buffer when it is full or not ready to accept commands.

Timeouts within Sub-peripherals: A bridge peripheral routed the request to an external SPI/I2C device that failed to acknowledge.

  4. DECERR (2'b11) — Decode Error
What it means:

The transaction address issued by the master does not correspond to any valid address aperture configured in the system.

Purpose:

Protects the bus from deadlock. If an unmapped address is accessed and no slave exists to drive ready, the system would hang indefinitely. The interconnect intercepts this condition, accepts the transfer through a dummy/default slave, and returns DECERR to gracefully terminate the bus cycle and notify the processor/master of the invalid address.

Typical scenarios:

Software pointer corruption (dereferencing a null pointer, wildcard address, or jumping outside mapped RAM).

Accessing an address hole between two peripheral base addresses (e.g., between 0x0001_FFFF and 0x0002_0000 when no device is mapped there).

In verification: Testbench address configuration macros (like S0_BASE to S3_HIGH) not matching the actual RTL crossbar parameter aperture windows.


